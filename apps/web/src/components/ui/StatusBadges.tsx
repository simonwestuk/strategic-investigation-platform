import { HYPOTHESIS_STATUS_LABELS, OPTION_REVIEW_LABELS, statusLabel } from "@/lib/labels";
import type {
  ChallengeStatus,
  ContradictionStatus,
  HypothesisOrigin,
  HypothesisStatus,
  OptionReviewStatus,
  Severity,
  TaskStatus,
} from "@/lib/types";
import { humanise } from "@/lib/format";
import { Badge, type Tone } from "./Badge";

const HYPOTHESIS_TONE: Record<HypothesisStatus, Tone> = {
  proposed: "muted",
  investigating: "info",
  supported: "ok",
  weakened: "warn",
  contradicted: "danger",
  unresolved: "muted",
  split: "accent",
};

const HYPOTHESIS_GLYPH: Record<HypothesisStatus, string> = {
  proposed: "○",
  investigating: "◔",
  supported: "✓",
  weakened: "↘",
  contradicted: "✕",
  unresolved: "?",
  split: "⑂",
};

export function HypothesisStatusBadge({ status }: { status: HypothesisStatus }) {
  return (
    <Badge tone={HYPOTHESIS_TONE[status]} className={status === "unresolved" ? "border-dashed" : undefined}>
      <span aria-hidden="true">{HYPOTHESIS_GLYPH[status]}</span> {HYPOTHESIS_STATUS_LABELS[status]}
    </Badge>
  );
}

export function OriginBadge({ origin }: { origin: HypothesisOrigin | "planner" | "challenger" | "human" }) {
  const tone: Tone = origin === "human" ? "accent" : origin === "challenger" ? "warn" : "muted";
  return <Badge tone={tone}>{humanise(origin)}</Badge>;
}

const RUN_STATUS_TONE: Record<string, Tone> = {
  draft: "muted",
  running: "info",
  awaiting_review: "warn",
  awaiting_decision: "warn",
  decided: "ok",
  closed: "muted",
  failed: "danger",
};

export function RunStatusBadge({ status }: { status: string }) {
  return (
    <Badge tone={RUN_STATUS_TONE[status] ?? "neutral"}>
      {status === "running" && <span aria-hidden="true" className="h-1.5 w-1.5 rounded-full bg-current" />}
      {statusLabel(status)}
    </Badge>
  );
}

const TASK_TONE: Record<TaskStatus, Tone> = {
  pending: "info",
  done: "ok",
  failed: "danger",
  skipped_duplicate: "muted",
  skipped_budget: "muted",
  blocked_unavailable: "warn",
};

export function TaskStatusBadge({ status }: { status: TaskStatus }) {
  return <Badge tone={TASK_TONE[status]}>{humanise(status)}</Badge>;
}

export function OptionReviewBadge({ status }: { status: OptionReviewStatus }) {
  const tone: Tone =
    status === "approved_for_decision" ? "ok" : status === "rejected" ? "danger" : status === "modified" ? "accent" : "warn";
  return <Badge tone={tone}>{OPTION_REVIEW_LABELS[status]}</Badge>;
}

export function SeverityBadge({ severity }: { severity: Severity }) {
  const tone: Tone = severity === "blocking" ? "danger" : severity === "major" ? "warn" : "muted";
  return <Badge tone={tone}>{humanise(severity)}</Badge>;
}

export function ChallengeStatusBadge({ status }: { status: ChallengeStatus }) {
  const tone: Tone = status === "open" ? "warn" : status === "dismissed_by_human" ? "muted" : "ok";
  return <Badge tone={tone}>{humanise(status)}</Badge>;
}

export function ContradictionStatusBadge({ status }: { status: ContradictionStatus }) {
  return <Badge tone={status === "unresolved" ? "warn" : "ok"}>{humanise(status)}</Badge>;
}

export function SyntheticBadge() {
  return (
    <Badge tone="muted" className="border-dashed" title="Synthetic demonstration source — not real-world data.">
      synthetic
    </Badge>
  );
}

/** Strategic options are AI recommendations. They are never decisions. */
export function AiRecommendationLabel() {
  return (
    <Badge tone="ai" title="Generated by the strategy agent. Only an accountable human can make a decision.">
      AI recommendation · not a decision
    </Badge>
  );
}

export function HumanDecisionLabel() {
  return (
    <span className="inline-flex items-center gap-1 rounded bg-human-bg px-1.5 py-px text-[11px] font-semibold text-human-fg">
      Human decision
    </span>
  );
}

export function ActorKindBadge({ kind }: { kind: string }) {
  if (kind === "human") return <Badge tone="accent">Human</Badge>;
  if (kind === "agent") return <Badge tone="ai">Agent</Badge>;
  return <Badge tone="muted">System</Badge>;
}
